import type { ApiForm, ApiMove, ApiSpecies, PokedexResponse } from '../pokedex/data'

/*
 * A small Pokédex for tests, shaped like the API's answer (GET /pokedex) with the real numbers of the Pokémon in it:
 * Megas, a Primal, regional forms, other forms (Giratina; Arceus with more than four), a looks-only costume, families,
 * nicknames, every category and an unreleased species.
 */

type FormInput = Partial<ApiForm> &
  Pick<ApiForm, 'id' | 'nameEn' | 'types' | 'attack' | 'defense' | 'stamina' | 'maxCp'>

function form(input: FormInput): ApiForm {
  return {
    kind: 'Base',
    isDefault: false,
    namePt: null,
    labelEn: null,
    labelPt: null,
    released: true,
    shadow: false,
    dynamax: false,
    gigantamax: false,
    sprite: null,
    spriteGigantamax: null,
    looksOnly: false,
    fastMoves: [],
    chargedMoves: [],
    ...input,
  }
}

function main(input: FormInput): ApiForm {
  return form({ isDefault: true, kind: 'Base', ...input })
}

function species(
  dex: number,
  nameEn: string,
  forms: ApiForm[],
  extra: Partial<Omit<ApiSpecies, 'dex' | 'nameEn' | 'forms'>> = {},
): ApiSpecies {
  return {
    dex,
    nameEn,
    namePt: nameEn,
    generation:
      dex <= 151 ? 1 : dex <= 251 ? 2 : dex <= 386 ? 3 : dex <= 493 ? 4 : dex <= 809 ? 7 : 8,
    category: 'None',
    familyId: `FAMILY_${nameEn.toUpperCase()}`,
    nicknames: [],
    forms,
    ...extra,
  }
}

